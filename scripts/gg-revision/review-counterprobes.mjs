// CODEX DRAFT — NOT CANON. Reviewer037 regressions against a FROZEN test input.
// Not a fresh corpus/export/release validator. Never modifies its input directory.
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { packetErrors, saveColourState } from './solver-packet.mjs';
import { renderContract } from './render-contract.tsx';
import { digest, sha256 } from './core.mjs';
const json=file=>JSON.parse(fs.readFileSync(file,'utf8'));
const here=fileURLToPath(import.meta.url);

if(process.argv[2]==='--check') {
  const [dir,input]=process.argv.slice(3),{entries,art}=json(path.join(input,'private-data.json'));
  const reference=json(path.join(input,'solver/manifest.json'));
  const originalMap=json(path.join(input,'private-mapping.json'));
  const contract=renderContract(entries,art,originalMap.assets,reference.rendererSha256,reference.basis);
  const manifest=json(path.join(dir,'solver/manifest.json')),mapping=json(path.join(dir,'private-mapping.json'));
  const errors=packetErrors(path.join(dir,'solver'),manifest,mapping,entries,reference.rendererSha256,contract);
  console.log(JSON.stringify({errors,scope:'Frozen input regression; no fresh corpus or browser observation'}));
  process.exitCode=errors.length?1:0;
} else {
  const [rawInput,rawOut]=process.argv.slice(2);
  assert.ok(rawInput&&rawOut,'Usage: review-counterprobes.mjs FROZEN_FIXTURE NEW_EXTERNAL_OUT');
  const input=fs.realpathSync(rawInput),out=path.resolve(rawOut),repo=path.resolve(import.meta.dirname,'../..');
  assert.ok(!fs.existsSync(out),'Fresh output directory required');
  assert.ok(!out.startsWith(repo+path.sep)&&!out.startsWith(input+path.sep)&&out!==repo&&out!==input,'External separate output required');
  fs.mkdirSync(out,{recursive:true});
  const results=[];
  const check=(dir,name)=>{
    const r=spawnSync(process.execPath,['--import',path.join(import.meta.dirname,'register.mjs'),here,'--check',dir,input],{encoding:'utf8'});
    fs.writeFileSync(path.join(out,name+'.log'),r.stdout+r.stderr);
    return {exit:r.status,...(r.stdout?JSON.parse(r.stdout):{error:r.stderr})};
  };
  const baseline=check(input,'baseline');
  assert.equal(baseline.exit,0,JSON.stringify(baseline));
  // Positive input is the historical browser capture, not output generated by
  // this expected-render function. Its old observation date remains explicit.
  const saved=path.join(out,'save-historical-observation');fs.mkdirSync(saved);
  fs.cpSync(path.join(input,'solver'),path.join(saved,'solver'),{recursive:true});
  const {entries,art}=json(path.join(input,'private-data.json'));
  const original=json(path.join(input,'solver/manifest.json')),originalMap=json(path.join(input,'private-mapping.json'));
  const contract=renderContract(entries,art,originalMap.assets,original.rendererSha256,original.basis);
  const entry=entries.find(e=>e.item.kind==='restore');
  const main=file=>{const html=fs.readFileSync(path.join(input,'solver',file),'utf8');return html.slice(html.indexOf('<main'),html.lastIndexOf('</main>')+7);};
  const observation={before:main('p008.html'),after:main('p008-s01.html'),action:{pickName:entry.item.name}};
  for(const bad of [{...observation,after:observation.before},{...observation,before:observation.after},
    {...observation,action:{pickColour:entry.item.colour}},{...observation,after:observation.after.replace('war rosa','war blau')}]) {
    assert.throws(()=>saveColourState(saved,entry.itemId,bad,entries,originalMap.assets,contract),/STATE:OBSERVED_TRANSITION/);
    assert.deepEqual(fs.readFileSync(path.join(saved,'solver/manifest.json')),fs.readFileSync(path.join(input,'solver/manifest.json')),'Rejected observation must not write');
  }
  saveColourState(saved,entry.itemId,observation,entries,originalMap.assets,contract);
  const savedCheck=check(saved,'saved-historical-observation');assert.equal(savedCheck.exit,0,JSON.stringify(savedCheck));
  const mutations=[
    ['S1-nested-public-key',({manifest})=>{manifest.label={label:'CODEX DRAFT — NOT CANON',notes:{p002:{answer:'pencil'}}};},'PACKET:PUBLIC_VALUES'],
    ['S2-aria-description-answer',({manifest,edit})=>{edit(manifest.views.find(v=>v.publicId==='p002'),s=>s.replace('<main ','<main aria-description="pencil" '));},'PUBLIC:RENDER_MISMATCH p002.html'],
    ['S3-empty-speaking-directory',({dir})=>{fs.mkdirSync(path.join(dir,'solver/p002-answer-pencil'));},'DIRECTORIES:UNEXPECTED: p002-answer-pencil/'],
    ['S4-initial-as-second-state',({dir,manifest,edit})=>{edit(manifest.states.find(s=>s.publicId==='p008'),()=>fs.readFileSync(path.join(dir,'solver/p008.html'),'utf8'));},'PUBLIC:RENDER_MISMATCH p008-s01.html'],
    ['S4-forged-caption-different-hash',({dir,manifest,edit})=>{edit(manifest.states.find(s=>s.publicId==='p008'),()=>fs.readFileSync(path.join(dir,'solver/p008.html'),'utf8').replace('1 · der Name','2 · die Farbe'));},'PUBLIC:RENDER_MISMATCH p008-s01.html'],
    ['S4-changed-colour-question',({manifest,edit})=>{edit(manifest.states.find(s=>s.publicId==='p008'),s=>s.replace('war rosa','war blau'));},'PUBLIC:RENDER_MISMATCH p008-s01.html'],
  ];
  for(const [name,change,wanted] of mutations) {
    const dir=path.join(out,name);fs.mkdirSync(dir);fs.cpSync(path.join(input,'solver'),path.join(dir,'solver'),{recursive:true});
    const manifest=json(path.join(input,'solver/manifest.json')),mapping=json(path.join(input,'private-mapping.json'));
    const edit=(row,fn)=>{const file=path.join(dir,'solver',row.file),before=fs.readFileSync(file,'utf8'),after=fn(before);assert.notEqual(after,before,'Mutation must change bytes');fs.writeFileSync(file,after);row.htmlSha256=sha256(after);};
    change({dir,manifest,edit});mapping.packetSha256=digest(manifest);
    fs.writeFileSync(path.join(dir,'solver/manifest.json'),JSON.stringify(manifest,null,2)+'\n');
    fs.writeFileSync(path.join(dir,'private-mapping.json'),JSON.stringify(mapping,null,2)+'\n');
    const actual=check(dir,name);results.push({name,...actual});
    assert.equal(actual.exit,1);assert.ok(actual.errors.includes(wanted),JSON.stringify(actual));
    assert.ok(!actual.errors.some(e=>e.startsWith('FILES:HASH')||e==='MAP:STALE_PACKET'),'Must fail on protection content, not stale hashes');
  }
  const originalAfter=check(input,'original-after');assert.equal(originalAfter.exit,0);
  const report={input,packetSha256:digest(json(path.join(input,'solver/manifest.json'))),baseline,savedCheck,rejectedSaveObservations:4,results,originalAfter,
    limit:'Historical input, current narrow checks. Fresh loader/export/browser/battery still required.'};
  fs.writeFileSync(path.join(out,'results.json'),JSON.stringify(report,null,2)+'\n');
  console.log(JSON.stringify({baseline:baseline.exit,mutations:results.map(({name,exit})=>({name,exit})),originalAfter:originalAfter.exit}));
}
